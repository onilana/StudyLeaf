@Composable
fun StudyLeafTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    content: @Composable () -> Unit
) {
    val colorScheme = if (darkTheme) StudyLeafDarkColorScheme else StudyLeafLightColorScheme
    val extendedColors = if (darkTheme) {
        StudyLeafExtendedColors(
            cardElevatedSurface = SurfaceContainerDark,
            cardHighSurface = SurfaceContainerHighDark
        )
    } else {
        StudyLeafExtendedColors(
            cardElevatedSurface = SurfaceContainerLight,
            cardHighSurface = SurfaceContainerHighLight
        )
    }

    val view = LocalView.current
    if (!view.isInEditMode) {
        SideEffect {
            val window = (view.context as? Activity)?.window
            if (window != null) {
                val controller = WindowCompat.getInsetsController(window, view)
                controller.isAppearanceLightStatusBars = !darkTheme
                controller.isAppearanceLightNavigationBars = !darkTheme
            }
        }
    }

    CompositionLocalProvider(LocalStudyLeafColors provides extendedColors) {
        MaterialTheme(
            colorScheme = colorScheme,
            typography = StudyLeafTypography,
            shapes = StudyLeafShapes,
            content = content
        )
    }
}

object StudyLeafThemeDefaults {
    val extendedColors: StudyLeafExtendedColors
        @Composable get() = LocalStudyLeafColors.current
}
